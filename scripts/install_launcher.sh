#!/usr/bin/env bash
# Install the `khunkhaar` launcher into the user's PATH.
#
# The installation path is resolved here, once, from this script's location - no other file
# hardcodes a home directory. Re-run this script if the KHUNKHAAR tree moves.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
PYTHON="$ROOT/.venv/bin/python"
TARGET_DIR="${KHUNKHAAR_BIN_DIR:-$HOME/.local/bin}"
TARGET="$TARGET_DIR/khunkhaar"

if [ ! -x "$PYTHON" ]; then
  echo "error: no virtualenv python at $PYTHON - run the Phase 1 install first" >&2
  exit 1
fi
if [ ! -f "$ROOT/core/cli.py" ]; then
  echo "error: $ROOT/core/cli.py is missing" >&2
  exit 1
fi

mkdir -p "$TARGET_DIR"
cat > "$TARGET" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install_launcher.sh - KHUNKHAAR QA $ROOT
set -euo pipefail
exec "$PYTHON" "$ROOT/core/cli.py" "\$@"
EOF
chmod 755 "$TARGET"

echo "installed $TARGET"
case ":$PATH:" in
  *":$TARGET_DIR:"*) ;;
  *) echo "warning: $TARGET_DIR is not on PATH - add it to your shell profile" >&2 ;;
esac

"$TARGET" --version
